#!/usr/bin/env python3
"""Tests for sync-hyprlock.py path discovery and font writes."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = Path(__file__).with_name("sync-hyprlock.py")

PALETTE = {
    "name": "Test",
    "bgBase": "#111111",
    "surface0": "#222222",
    "accentBlue": "#89b4fa",
    "accentGreen": "#a6e3a1",
    "accentRed": "#f38ba8",
    "accentYellow": "#f9e2af",
    "accentCyan": "#89dceb",
    "fgPrimary": "#cdd6f4",
    "fgSecondary": "#bac2de",
    "fgTertiary": "#a6adc8",
}


def _write_palette_settings(home: Path, ui_font: str = "Inter") -> None:
    yahr = home / ".config" / "yahr"
    yahr.mkdir(parents=True)
    (yahr / "current.json").write_text(json.dumps(PALETTE) + "\n")
    (yahr / "settings.json").write_text(json.dumps({"general": {"uiFont": ui_font}}) + "\n")
    (home / ".config" / "hypr").mkdir(parents=True, exist_ok=True)


class SyncHyprlockTests(unittest.TestCase):
    def test_writes_settings_ui_font_from_repo_script(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp) / "home"
            _write_palette_settings(home, "Space Grotesk")
            (home / ".config" / "yahr" / "repo-root").write_text(str(ROOT) + "\n")

            env = os.environ.copy()
            env["HOME"] = str(home)
            result = subprocess.run(
                ["python3", str(SCRIPT), "--ui-font", "Space Grotesk"],
                env=env,
                text=True,
                capture_output=True,
                check=False,
                cwd=str(ROOT),
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            text = (home / ".config" / "hypr" / "hyprlock.conf").read_text()
            self.assertIn("$ui = Space Grotesk", text)
            self.assertIn("$uiBold = Space Grotesk", text)
            self.assertNotIn("Inter ExtraBold", text)
            self.assertNotIn("ExtraBold", text)

    def test_copied_quickshell_uses_repo_root_engine(self) -> None:
        """~/.config/quickshell copy must not break imports (parents[2] == ~/.config)."""
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp) / "home"
            _write_palette_settings(home, "Manrope")
            (home / ".config" / "yahr" / "repo-root").write_text(str(ROOT) + "\n")

            qs_scripts = home / ".config" / "quickshell" / "scripts"
            qs_scripts.mkdir(parents=True)
            shutil.copy2(SCRIPT, qs_scripts / "sync-hyprlock.py")

            env = os.environ.copy()
            env["HOME"] = str(home)
            result = subprocess.run(
                ["python3", str(qs_scripts / "sync-hyprlock.py"), "--ui-font", "Manrope"],
                env=env,
                text=True,
                capture_output=True,
                check=False,
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            text = (home / ".config" / "hypr" / "hyprlock.conf").read_text()
            self.assertIn("$ui = Manrope", text)
            self.assertIn("wrote", result.stdout)

    def test_patches_existing_conf_without_theme_engine(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            home = Path(tmp) / "home"
            _write_palette_settings(home, "Roboto")
            # Point repo-root at an empty tree so find_theme_engine skips it
            # and there is no share package either → pure patch path.
            empty = Path(tmp) / "empty-repo"
            (empty / "theme-engine").mkdir(parents=True)
            (home / ".config" / "yahr" / "repo-root").write_text(str(empty) + "\n")
            conf = home / ".config" / "hypr" / "hyprlock.conf"
            conf.write_text(
                "# Generated by yahr-theme\n"
                "$font = Maple Mono NF\n"
                "$ui = Inter\n"
                "$icons = Symbols Nerd Font\n"
                "label {\n"
                "    font_family = Inter ExtraBold\n"
                "}\n"
                "label {\n"
                "    font_family = $ui\n"
                "}\n"
            )

            env = os.environ.copy()
            env["HOME"] = str(home)
            # Run from /tmp so Path(__file__).parents[2] is not the real repo
            # when the script is the repo copy — use a relocated script.
            relocated = Path(tmp) / "relocated" / "scripts"
            relocated.mkdir(parents=True)
            shutil.copy2(SCRIPT, relocated / "sync-hyprlock.py")
            result = subprocess.run(
                ["python3", str(relocated / "sync-hyprlock.py"), "--ui-font", "Roboto"],
                env=env,
                text=True,
                capture_output=True,
                check=False,
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            text = conf.read_text()
            self.assertIn("$ui = Roboto", text)
            self.assertIn("$uiBold = Roboto", text)
            self.assertIn("font_family = $uiBold", text)
            self.assertNotIn("Inter ExtraBold", text)
            self.assertIn("patched", result.stdout)


if __name__ == "__main__":
    unittest.main()
